-- Single-table schema for the savings-account API.
-- Managed here rather than via Hibernate ddl-auto so the DB shape is explicit and reviewable.
-- TODO(infra): replace with Flyway/Liquibase once this leaves the exercise stage.

CREATE TABLE IF NOT EXISTS savings_accounts (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_uid    UUID         NOT NULL,           -- opaque external id (never the identity column)
    account_number VARCHAR(20)  NOT NULL,
    customer_name  VARCHAR(100) NOT NULL,
    nickname       VARCHAR(30),                    -- optional
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version        BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT uq_savings_accounts_account_number UNIQUE (account_number),
    CONSTRAINT uq_savings_accounts_account_uid UNIQUE (account_uid)
);

-- count-by-customer lookups (max-5 rule) match on upper(customer_name), so the
-- index must be functional to serve them - a bare-column index cannot.
-- Also shortens advisory-lock hold time on the create path.
CREATE INDEX IF NOT EXISTS idx_savings_accounts_customer_upper
    ON savings_accounts (upper(customer_name));

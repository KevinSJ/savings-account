package com.takehome.savings.domain;

import java.time.Instant;
import java.util.Objects;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;
import jakarta.persistence.Version;

import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

/**
 * A savings account. Persisted as a single row in a single table
 * ({@code savings_accounts}), per the requirements.
 *
 * <p>Invariants held here:
 * <ul>
 *   <li>{@code id} and {@code accountNumber} are always generated by the API/server side,
 *       never accepted from the caller.</li>
 *   <li>{@code customerName} is mandatory (non-null).</li>
 *   <li>{@code nickname} is optional; a blank nickname is normalised to {@code null} so the
 *       column stores absence, not an empty string.</li>
 * </ul>
 *
 * <p>Business rules that span multiple rows (max 5 accounts per customer) deliberately live
 * in {@code AccountService}, not here - an entity only knows about itself.
 */
@Entity
@Table(
        name = "savings_accounts",
        uniqueConstraints = @UniqueConstraint(
                name = "uq_savings_accounts_account_number",
                columnNames = "account_number"))
// Indexes are owned by db/schema.sql (which can express the functional
// upper(customer_name) index the quota query needs) - not duplicated here.
public class SavingsAccount {

    /** Surrogate key, autogenerated by the database. */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /** Public-facing account identifier, autogenerated by the API. Unique, Luhn-checked. */
    @Column(name = "account_number", nullable = false, updatable = false, length = 20)
    private String accountNumber;

    /** Mandatory. The customer is currently identified by their name - see docs/DESIGN-TRADEOFFS.md. */
    @Column(name = "customer_name", nullable = false, length = 100)
    private String customerName;

    /** Optional human-friendly label (5-30 chars when present). */
    @Column(name = "nickname", length = 30)
    private String nickname;

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @UpdateTimestamp
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    /**
     * Optimistic-lock counter. There is no mutation endpoint today, but retrofitting
     * optimistic locking onto a live table is far more painful than carrying the column.
     */
    @Version
    @Column(name = "version", nullable = false)
    private long version;

    /** Required by JPA. Never called by application code. */
    protected SavingsAccount() {
        // JPA proxy instantiation.
    }

    private SavingsAccount(String accountNumber, String customerName, String nickname) {
        this.accountNumber = Objects.requireNonNull(accountNumber, "accountNumber");
        this.customerName = Objects.requireNonNull(customerName, "customerName");
        this.nickname = normalizeNickname(nickname);
    }

    /**
     * Factory for a brand-new account. Only the service layer may call this, after it has
     * generated an account number and applied all business validation.
     */
    public static SavingsAccount openNew(String accountNumber, String customerName, String nickname) {
        return new SavingsAccount(accountNumber, customerName, nickname);
    }

    /**
     * Blank means "no nickname": normalise to {@code null} instead of storing "".
     */
    private static String normalizeNickname(String nickname) {
        if (nickname == null) {
            return null;
        }
        String trimmed = nickname.strip();
        return trimmed.isEmpty() ? null : trimmed;
    }

    public Long getId() {
        return id;
    }

    public String getAccountNumber() {
        return accountNumber;
    }

    public String getCustomerName() {
        return customerName;
    }

    public String getNickname() {
        return nickname;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }

    /**
     * Exposed so the Redis cache serialiser includes it: cache hits are rebuilt
     * reflectively (no setters by design), and without this getter the version
     * would silently read 0 on every hit (review finding #9).
     */
    public long getVersion() {
        return version;
    }
}

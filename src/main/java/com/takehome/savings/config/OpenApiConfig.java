package com.takehome.savings.config;

import java.util.LinkedHashMap;
import java.util.Map;

import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.info.Contact;
import io.swagger.v3.oas.models.info.Info;
import io.swagger.v3.oas.models.media.ArraySchema;
import io.swagger.v3.oas.models.media.BooleanSchema;
import io.swagger.v3.oas.models.media.DateTimeSchema;
import io.swagger.v3.oas.models.media.IntegerSchema;
import io.swagger.v3.oas.models.media.ObjectSchema;
import io.swagger.v3.oas.models.media.Schema;
import io.swagger.v3.oas.models.media.StringSchema;
import io.swagger.v3.oas.models.servers.Server;

import org.springdoc.core.customizers.OpenApiCustomizer;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

/**
 * OpenAPI document metadata.
 *
 * <p>The document itself is not written by hand: springdoc derives it from the
 * controller and DTO annotations at runtime, which is the only way the published
 * contract cannot drift from the implemented surface. Regenerate the checked-in
 * copy with {@code ./gradlew generateOpenApi} after changing any annotated type.
 */
@Configuration
public class OpenApiConfig {

    private static final String DESCRIPTION = """
            Take-home exercise API. Documents the features actually implemented in this
            repository - no aspirational endpoints.

            Domain rules implemented server-side:
            * `id` and `accountNumber` are generated by the API (never accepted from
              callers). The VALUE of `id` is an opaque UUIDv4 and the internal
              sequential id never crosses the API boundary - URL enumeration has no
              foothold.
            * Response minimisation: the CREATE response body carries the account
              number only. The generated `id` travels exactly once, in the `Location`
              header; GET returns the full account data model.
            * `accountNumber` is 12 digits ending in a Luhn check digit.
            * `customerName` is mandatory; name identity is canonicalised (unicode NFKC
              fold, whitespace runs collapsed) and matched case-insensitively.
            * A customer may hold at most **5** savings accounts (enforced with a
              Postgres advisory lock; concurrent creations are safe).
            * `nickname` is optional; when present it must be 5-30 characters and pass
              an offensive-term screen.

            Error contract: every failure maps to RFC 9457 `application/problem+json`
            with a stable `type` URI. 503 responses carry `retryable: true` when the
            situation is transient (datastore outage, lock contention, allocation races).

            Security note: this exercise has no authn/authz (documented in
            `docs/DESIGN-TRADEOFFS.md` A7); read paths emit `Cache-Control: no-store, private`.
            """;

    @Bean
    OpenAPI savingsAccountsOpenApi() {
        return new OpenAPI()
                .info(new Info()
                        .title("Savings Account API")
                        .version("1.0.0")
                        .summary("Create and read savings bank accounts")
                        .description(DESCRIPTION)
                        .contact(new Contact()
                                .name("repository docs")
                                .url("https://github.com/takehome/savings-accounts/blob/main/docs/ARCHITECTURE.md")))
                .addServersItem(new Server()
                        .url("http://localhost:8080")
                        .description("Local docker compose stack"));
    }

    /**
     * Documents the RFC 9457 extension members on the generated {@code ProblemDetail}
     * schema. springdoc derives the base shape (type/title/status/detail/instance) from
     * Spring's {@code ProblemDetail}; the members this API adds are invisible to it, so
     * they are declared here rather than in a hand-maintained document.
     */
    @Bean
    OpenApiCustomizer problemDetailContract() {
        return openApi -> {
            if (openApi.getComponents() == null || openApi.getComponents().getSchemas() == null) {
                return;
            }
            Schema<?> problem = openApi.getComponents().getSchemas().get("ProblemDetail");
            if (problem == null) {
                return;
            }
            problem.setDescription("""
                    RFC 9457 problem document. `type` is always a stable URI under
                    https://api.takehome.co.nz/errors/. Extension members: `issues` (bean
                    validation), `retryable` (transient 503s), `customerName` + `maxAccounts`
                    (quota), `timestamp`.""");
            problem.addProperty("timestamp", new DateTimeSchema()
                    .description("When the failure was rendered, server clock (UTC)")
                    .example("2026-11-06T10:00:00Z"));
            problem.addProperty("retryable", new BooleanSchema()
                    .description("Present and true when retrying the same request may succeed"));
            problem.addProperty("issues", new ArraySchema()
                    .description("Present on `validation-failed`; one entry per rejected field")
                    .items(new ObjectSchema()
                            .addProperty("field", new StringSchema().example("customerName"))
                            .addProperty("message", new StringSchema()
                                    .example("customerName is mandatory"))));
            problem.addProperty("customerName", new StringSchema()
                    .description("Present on `account-limit-reached`: the customer at the quota")
                    .example("Alice Tester"));
            problem.addProperty("maxAccounts", new IntegerSchema()
                    .description("Present on `account-limit-reached`: the quota that was hit")
                    .example(5));
            // Ordered map on purpose: Map.of() iterates in a per-JVM random order, which
            // makes the generated document differ between runs and breaks the
            // verifyOpenApi diff gate for no reason.
            Map<String, Object> example = new LinkedHashMap<>();
            example.put("type", "https://api.takehome.co.nz/errors/account-limit-reached");
            example.put("title", "Conflict");
            example.put("status", 409);
            example.put("detail", "Customer 'Alice Tester' already holds the maximum of 5 savings accounts");
            example.put("customerName", "Alice Tester");
            example.put("maxAccounts", 5);
            example.put("timestamp", "2026-11-06T10:00:00Z");
            problem.setExample(example);
        };
    }
}
